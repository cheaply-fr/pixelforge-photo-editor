// Regenerate src/fontLibrary.generated.ts from scripts/font-catalog.mjs and
// the pinned font packages in node_modules. Run after changing the catalogue
// or bumping a font package: `npm run fonts:sync`.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FONT_CATALOG } from './font-catalog.mjs';
import { familyCoverage, iconIndex, resolveCatalogEntry } from './lib/font-meta.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function resolveLibrary(projectRoot = root) {
  const ranges = [];
  const resolved = FONT_CATALOG.map((entry) => resolveCatalogEntry(entry, projectRoot, ranges));
  return { resolved, ranges };
}

export function registryFromResolved(resolved, projectRoot = root, ranges = []) {
  return resolved.map((item) => {
    const { iconSource, ...font } = item.font;
    if (font.sample) {
      const coverage = familyCoverage(projectRoot, item.copies);
      for (const char of font.sample)
        if (!coverage.has(char.codePointAt(0))) throw new Error(`${font.family}: sample glyph U+${char.codePointAt(0).toString(16)} is not in the font`);
    }
    if (font.category === 'icons') {
      const count = iconIndex(projectRoot, item).length;
      font.icons = { kind: 'named', count, ...(iconSource.startsWith('font-awesome') ? { attribution: 'Icons: Font Awesome Free, CC BY 4.0 (fontawesome.com/license/free)' } : {}) };
    } else if (font.category === 'symbols') {
      const coverage = familyCoverage(projectRoot, item.copies);
      // Count only glyphs a shipped face renders (subset files carry extras
      // outside their unicode-range), matching the Glyphs panel.
      const allowed = font.faces.every((face) => face.r >= 0)
        ? font.faces.flatMap((face) =>
            ranges[face.r].split(',').map((part) => {
              const [start, end = start] = part.replace('U+', '').split('-').map((hex) => Number.parseInt(hex, 16));
              return [start, end];
            }),
          )
        : undefined;
      const rendered = (cp) => !allowed || allowed.some(([start, end]) => cp >= start && cp <= end);
      font.icons = { kind: 'unicode-blocks', count: [...coverage.keys()].filter((cp) => cp > 0x7f && rendered(cp)).length };
    }
    return font;
  });
}

export function assetVersion(registry) {
  const hash = createHash('sha256');
  // Covers files, sizes, versions and glyph metadata, so URLs (and the
  // immutable caches behind them) change whenever anything served changes.
  hash.update(JSON.stringify(registry));
  return hash.digest('hex').slice(0, 10);
}

export function generatedSource(registry, ranges) {
  return `// Generated by scripts/sync-font-library.mjs from scripts/font-catalog.mjs.
// Do not edit by hand: run \`npm run fonts:sync\`.
/* eslint-disable */
export const FONT_ASSET_VERSION = ${JSON.stringify(assetVersion(registry))};
export const FONT_UNICODE_RANGES: readonly string[] = ${JSON.stringify(ranges)};
export const GENERATED_FONT_LIBRARY = ${JSON.stringify(registry)} as const;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { resolved, ranges } = resolveLibrary();
  const registry = registryFromResolved(resolved, root, ranges);
  writeFileSync(path.join(root, 'src', 'fontLibrary.generated.ts'), generatedSource(registry, ranges));
  const bytes = registry.reduce((sum, font) => sum + font.faces.reduce((total, face) => total + face.b, 0), 0);
  console.log(`Font library: ${registry.length} families, ${registry.reduce((n, f) => n + f.faces.length, 0)} files, ${(bytes / 1048576).toFixed(2)} MiB`);
}
